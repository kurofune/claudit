function replaceHash() {
  const want = spendHash(tab, unit);
  if (window.location.hash !== want) history.replaceState(history.state, '', want);
}

function syncToggle() {
  container.querySelectorAll('.unit-opt').forEach(b => {
    const on = b.dataset.unit === unit;
    b.setAttribute('aria-checked', on ? 'true' : 'false');
    b.tabIndex = on ? 0 : -1;
    b.classList.toggle('is-active', on);
  });
}

function syncTabs() {
  container.querySelectorAll('.subtab[data-subtab]').forEach(a => {
    a.classList.toggle('is-active', a.dataset.subtab === tab);
    a.setAttribute('href', spendHash(a.dataset.subtab, unit));
  });
  container.querySelectorAll('.subview').forEach(s =>
    s.classList.toggle('is-active', s.dataset.subview === tab));
}


// ─── Nav metric ────────────────────────────────────────────────────────

function navMetricText(core, u) {
  if (u === 'tokens') return fmtCompact((core.tokens && core.tokens.total) || 0);
  const byModel = (core.cost && core.cost.by_model) || [];
  const top = byModel.filter(r => r.CostUSD > 0)[0];
  return top ? `${truncate(top.Model, 18)} · ${fmtMoney(top.CostUSD)}` : '—';
}

function writeNavMetric(core, u) {
  const el = document.getElementById('nav-metric-cost');
  if (el) el.textContent = navMetricText(core, u);
}

// paintNav resolves the sidebar metric at startup, in the unit the
// initial hash names, before the user opens Spend.
export async function paintNav() {
  let core;
  try { core = await loadCore(); } catch { return; }
  if (container) return; // paint() owns the metric once the view exists
  const r = parseHash();
  writeNavMetric(core, r.view === 'spend' ? r.unit : 'dollars');
}


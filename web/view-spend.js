// loadCore fetches the two payloads the nav metric needs in either
// unit. A failure clears the memo so the next call retries.
function loadCore() {
  if (!corePromise) {
    corePromise = Promise.all([fetchCost(), fetchTokens()])
      .then(([cost, tokens]) => ({ cost, tokens }))
      .catch(err => { corePromise = null; throw err; });
  }
  return corePromise;
}

// loadAll adds the Dollars-only extras (sparkline trends, subagents),
// fetched in parallel with the core. Extras failing degrades quietly.
function loadAll() {
  if (!fullPromise) {
    fullPromise = Promise.all([
      loadCore(),
      fetchTrends('model').catch(() => null),
      fetchTrends('project').catch(() => null),
      fetchSubagents().catch(() => null),
    ]).then(([core, modelTrends, projectTrends, subagents]) => ({
      ...core, modelTrends, projectTrends, subagents,
      period: (modelTrends && modelTrends.period) || (projectTrends && projectTrends.period) || '',
    })).catch(err => { fullPromise = null; throw err; });
  }
  return fullPromise;
}


function fillDollars(d) {
  const cost = d.cost || {};
  const totalCost = cost.total_cost_usd || 0;
  const byModel = withShare(cost.by_model || [], 'Pct', totalCost);
  const byProject = withShare(cost.by_project || [], 'Pct', totalCost);
  const bySkill = cost.by_skill || [];
  const byPrompt = withShare(cost.by_prompt || [], 'Pct', totalCost);
  const opts = { emptyText: EMPTY_TEXT };
  const { period, modelTrends, projectTrends, subagents } = d;

  const modelTable = tableEl('model');
  const projectTable = tableEl('project');
  if (period) {
    injectTrendColumn(modelTable, 'OutputTokens', period);
    injectTrendColumn(projectTable, 'DominantModel', period);
  }

  buildRows(modelTable, byModel, r => withTrend([
    [escHtml(r.Model), false],
    [escHtml(fmtMoney(r.CostUSD)), true, r.CostUSD],
    [pct(r.CostUSD, totalCost), true],
    [fmtNum(r.Turns), true],
    [fmtNum(r.OutputTokens), true],
    [fmtNum(r.CacheReadTokens), true],
  ], 4, modelTrends && modelTrends.series ? modelTrends.series[r.Model] : null, period, trendSpark), opts);

  buildRows(projectTable, byProject, r => withTrend([
    [`<span class="truncate path" title="${escHtml(r.Project)}">${escHtml(r.Project)}</span>`, false],
    [escHtml(fmtMoney(r.CostUSD)), true, r.CostUSD],
    [pct(r.CostUSD, totalCost), true],
    [fmtNum(r.Sessions), true],
    [fmtNum(r.Turns), true],
    [escHtml(r.DominantModel), false],
  ], 5, projectTrends && projectTrends.series ? projectTrends.series[r.Project] : null, period, trendSpark), opts);

  buildRows(tableEl('skill'), bySkill, r => [
    [`<code>${escHtml(r.Key)}</code>`, false],
    [fmtNum(r.Count), true],
    [fmtNum(r.TurnCount), true],
    [escHtml(fmtMoney(r.CostUSD)), true, r.CostUSD],
    [fmtNum(r.OutputTokens), true],
  ], opts);

  buildRows(tableEl('prompt'), byPrompt, r => {
    const sample = r.Sample || r.Key || '';
    const head = sample.length > 80 ? sample.slice(0, 79) + '…' : sample;
    return [
      [`<span title="${escHtml(sample)}">${escHtml(head)}</span>`, false],
      [fmtNum(r.Invocations), true],
      [fmtNum(r.Sessions), true],
      [fmtNum(r.TurnCount), true],
      [escHtml(fmtMoney(r.CostUSD)), true, r.CostUSD],
      [pct(r.CostUSD, totalCost), true],
    ];
  }, opts);

  fillSubagents(subagents, totalCost);
  paintBars(currentFilter());
}

function fillSubagents(subagents, totalCost) {
  const unavailable = { emptyText: 'Subagent data unavailable' };
  const stacked = container.querySelector('#stacked-main');
  const mainsideBody = container.querySelector('[data-table="mainside"] tbody');
  if (!subagents) {
    if (stacked) stacked.innerHTML = '';
    if (mainsideBody) mainsideBody.innerHTML = emptyRow(5, unavailable.emptyText);
    buildRows(tableEl('subagent'), [], () => [], unavailable);
    buildRows(tableEl('invocation'), [], () => [], unavailable);
    return;
  }
  const opts = { emptyText: EMPTY_TEXT };
  const sideCost = (subagents.sidechain && subagents.sidechain.cost) || 0;
  const bySub = withShare(subagents.by_subagent || [], 'PctSide', sideCost);
  const invs = subagents.agent_invocations || [];
  const main = subagents.main || { cost: 0, turns: 0, tokens: {} };
  const side = subagents.sidechain || { cost: 0, turns: 0, tokens: {} };
  const totalMainSide = subagents.main_side_cost || 0;

  if (stacked) {
    if (totalMainSide > 0) {
      const mp = 100 * main.cost / totalMainSide;
      const sp = 100 - mp;
      stacked.innerHTML = `
        <div class="bucket bucket-main" style="width:${mp}%" title="main: ${escHtml(fmtMoney(main.cost))}">main · ${mp.toFixed(1)}%</div>
        <div class="bucket bucket-side" style="width:${sp}%" title="sidechain: ${escHtml(fmtMoney(side.cost))}">sidechain · ${sp.toFixed(1)}%</div>`;
    } else {
      stacked.innerHTML = '';
    }
  }

  // Mainside table — no sort (the rows are fixed: main, sidechain).
  if (mainsideBody) {
    if ((main.turns || 0) + (side.turns || 0) === 0) {
      mainsideBody.innerHTML = emptyRow(5, EMPTY_TEXT);
    } else {
      const buckets = [
        ['main', main.cost, main.turns, (main.tokens || {}).CacheReadTokens || 0],
        ['sidechain', side.cost, side.turns, (side.tokens || {}).CacheReadTokens || 0],
      ];
      mainsideBody.innerHTML = buckets.map(([n, c, t, cr]) =>
        `<tr data-cost="${c}"><td>${n}</td><td class="num">${escHtml(fmtMoney(c))}</td><td class="num">${fmtPct(c, totalMainSide)}</td><td class="num">${fmtNum(t)}</td><td class="num">${fmtNum(cr)}</td></tr>`
      ).join('');
    }
  }

  buildRows(tableEl('subagent'), bySub, r => [
    [escHtml(r.Type), false],
    [escHtml(fmtMoney(r.CostUSD)), true, r.CostUSD],
    [pct(r.CostUSD, sideCost), true],
    [fmtNum(r.Turns), true],
    [fmtNum(r.OutputTokens), true],
    [fmtNum(r.CacheReadTokens), true],
  ], opts);

  buildRows(tableEl('invocation'), invs, r => [
    [escHtml(r.SubagentType || '(unknown)'), false],
    [`<span title="${escHtml(r.Description)}">${escHtml(truncate(r.Description, 80))}</span>`, false],
    [escHtml(fmtMoney(r.CostUSD)), true, r.CostUSD],
    [fmtNum(r.Turns), true],
    [`<span class="truncate path" title="${escHtml(r.Project)}">${escHtml(truncate(r.Project, 80))}</span>`, false],
    [fmtDate(r.First), false],
  ], opts);
}


func bashTurn(uuid, sid string, ts time.Time, toolID, cmd string) parse.Turn {
	t := mkTurn(uuid, sid, "/root/-p-x/"+sid+".jsonl", ts)
	t.ToolUses = []parse.ToolUse{{ID: toolID, Name: "Bash", Input: cmd}}
	return t
}

func findRow(t *testing.T, idx SessionIndex, sid string) SessionIndexRow {
	t.Helper()
	for _, r := range idx.Sessions {
		if r.SessionID == sid {
			return r
		}
	}
	t.Fatalf("session %s missing from index %+v", sid, idx.Sessions)
	return SessionIndexRow{}
}

// TestBuildSessionIndex_FailedCountsOnlyUnresolvedErrors: an errored Bash
// call that later re-ran with the identical input and succeeded is resolved;
// an errored call never re-run with the same input stays failed.
func TestBuildSessionIndex_FailedCountsOnlyUnresolvedErrors(t *testing.T) {
	prices, _ := pricing.LoadDefault()
	t0 := time.Date(2026, 5, 1, 12, 0, 0, 0, time.UTC)
	snap := &corpus.Snapshot{
		Turns: []parse.Turn{
			bashTurn("a1", "fixed", t0, "t1", "go test ./..."),
			bashTurn("a2", "fixed", t0.Add(time.Minute), "t2", "go test ./..."),
			bashTurn("b1", "broken", t0, "t3", "go test ./..."),
			bashTurn("b2", "broken", t0.Add(time.Minute), "t4", "go test -run X ./..."),
		},
		ToolResults: []parse.ToolResult{
			{ToolUseID: "t1", IsError: true, Content: "FAIL"},
			{ToolUseID: "t2", Content: "ok"},
			{ToolUseID: "t3", IsError: true, Content: "FAIL"},
			{ToolUseID: "t4", Content: "ok"},
		},
	}
	idx := BuildSessionIndex(snap, prices, aggregate.Filter{}, IndexOptions{})
	if got := findRow(t, idx, "fixed").Failed; got != 0 {
		t.Errorf("fixed: failed = %d, want 0 (the same input later succeeded)", got)
	}
	if got := findRow(t, idx, "broken").Failed; got != 1 {
		t.Errorf("broken: failed = %d, want 1 (the errored input never re-ran)", got)
	}
}

// TestBuildSessionIndex_FamilyFallsBackPastCaveat: a session whose first user
// message is only a caveat block keys on its next prompt with text; a session
// with no textual prompt keys "(no prompt)".
func TestBuildSessionIndex_FamilyFallsBackPastCaveat(t *testing.T) {
	prices, _ := pricing.LoadDefault()
	t0 := time.Date(2026, 5, 1, 12, 0, 0, 0, time.UTC)
	snap := &corpus.Snapshot{
		Turns: []parse.Turn{
			mkTurn("a1", "caveat", "/root/-p-x/caveat.jsonl", t0.Add(2*time.Second)),
			mkTurn("b1", "silent", "/root/-p-x/silent.jsonl", t0),
		},
		Users: []parse.UserMessage{
			// Out of order on purpose: the index orders prompts by time.
			{SessionID: "caveat", UUID: "u2", Timestamp: t0.Add(time.Second), Text: "work bead djinn-bhl6v", SourceFile: "/root/-p-x/caveat.jsonl"},
			{SessionID: "caveat", UUID: "u1", Timestamp: t0, Text: "<local-command-caveat>Caveat: generated by local commands.</local-command-caveat>", SourceFile: "/root/-p-x/caveat.jsonl"},
			{SessionID: "silent", UUID: "u3", Timestamp: t0, Text: "<system-reminder>hook output</system-reminder>", SourceFile: "/root/-p-x/silent.jsonl"},
		},
	}
	idx := BuildSessionIndex(snap, prices, aggregate.Filter{}, IndexOptions{})
	c := findRow(t, idx, "caveat")
	if c.FamilyKey != "work bead _" || c.Remainder != "djinn-bhl6v" || c.Title != "work bead djinn-bhl6v" {
		t.Errorf("caveat row = key %q remainder %q title %q, want the next prompt's", c.FamilyKey, c.Remainder, c.Title)
	}
	if s := findRow(t, idx, "silent"); s.FamilyKey != "(no prompt)" || s.Title != "" {
		t.Errorf("silent row = key %q title %q, want (no prompt) and no title", s.FamilyKey, s.Title)
	}
}

// TestBuildSessionIndex_RowFields: one row per session with its numbers, a
// sub-agent's prompt and turns folded into its parent, newest first.
func TestBuildSessionIndex_RowFields(t *testing.T) {
	prices, _ := pricing.LoadDefault()
	root := t.TempDir()
	t0 := time.Date(2026, 5, 1, 12, 0, 0, 0, time.UTC)
	mainFile := root + "/-p-x/s1.jsonl"
	subFile := writeSubagent(t, root+"/-p-x", "s1", "x1", `{"agentType":"Explore","description":"look"}`)

	a1 := bashTurn("a1", "s1", t0.Add(time.Second), "t1", "ls")
	a1.SourceFile, a1.CWD, a1.Model = mainFile, "/p/x", "claude-opus-4-7"
	a1.ToolUses = append(a1.ToolUses, parse.ToolUse{ID: "t2", Name: "Read", Input: "/p/x/a.go"})
	sub := mkTurn("x1", "s1", subFile, t0.Add(2*time.Second))
	sub.Model = "claude-haiku-4-5"
	sub.ToolUses = []parse.ToolUse{{ID: "t3", Name: "Grep", Input: "foo"}}
	a2 := mkTurn("a2", "s1", mainFile, t0.Add(10*time.Second))
	a2.Model, a2.Text = "claude-opus-4-7", "\nAll tests pass.\nDetails follow."
	a3 := mkTurn("a3", "s1", mainFile, t0.Add(20*time.Second))
	a3.Model = "claude-opus-4-7" // tool-only last turn: outcome keeps a2's text
	other := mkTurn("o1", "s0", "/root/-p-y/s0.jsonl", t0.Add(-time.Hour))

	snap := &corpus.Snapshot{
		Turns: []parse.Turn{a1, sub, a2, a3, other},
		Users: []parse.UserMessage{
			{SessionID: "s1", UUID: "u1", Timestamp: t0, Text: "fix the login bug\nmore detail", SourceFile: mainFile},
			{SessionID: "s1", UUID: "su", Timestamp: t0.Add(time.Second), Text: "sub-agent prompt first", SourceFile: subFile},
		},
	}
	now := t0.Add(50 * time.Second)
	idx := BuildSessionIndex(snap, prices, aggregate.Filter{}, IndexOptions{Now: now, ActiveWindow: time.Minute})
	if len(idx.Sessions) != 2 || idx.Sessions[0].SessionID != "s1" || idx.Sessions[1].SessionID != "s0" {
		t.Fatalf("sessions = %+v, want s1 then s0 (newest last_activity first)", idx.Sessions)
	}
	r := idx.Sessions[0]
	oneTurn, _ := prices.Cost("claude-opus-4-7", 1000, 0, 0, 0, 0)
	haikuTurn, _ := prices.Cost("claude-haiku-4-5", 1000, 0, 0, 0, 0)
	if d := r.CostUSD - (3*oneTurn + haikuTurn); d > 1e-9 || d < -1e-9 {
		t.Errorf("cost = %v, want %v", r.CostUSD, 3*oneTurn+haikuTurn)
	}
	checks := []struct {
		name      string
		got, want any
	}{
		{"family_key", r.FamilyKey, "fix the login bug"},
		{"remainder", r.Remainder, ""},
		{"title", r.Title, "fix the login bug"},
		{"outcome", r.Outcome, "All tests pass."},
		{"project", r.Project, "x"},
		{"provider", r.Provider, "claude-code"},
		{"model", r.Model, "claude-opus-4-7"},
		{"duration_ms", r.DurationMs, int64(19000)},
		{"turns", r.Turns, 4},
		{"commands", r.Commands, 3},
		{"failed", r.Failed, 0},
		{"last_activity", r.LastActivity, t0.Add(20 * time.Second)},
		{"started_at", r.StartedAt, t0.Add(time.Second)},
		{"active", r.Active, true},
	}
	for _, c := range checks {
		if c.got != c.want {
			t.Errorf("%s = %v, want %v", c.name, c.got, c.want)
		}
	}
	if idx.Sessions[1].Active {
		t.Errorf("s0 active, want inactive (an hour old)")
	}
}

// TestBuildSessionIndex_RowCarriesNoStepsOrSnippets: the index is one light
// row per session — no steps, tools, inputs or outputs reach the wire.
func TestBuildSessionIndex_RowCarriesNoStepsOrSnippets(t *testing.T) {
	prices, _ := pricing.LoadDefault()
	t0 := time.Date(2026, 5, 1, 12, 0, 0, 0, time.UTC)
	turn := bashTurn("a1", "s1", t0, "t1", "echo SECRET-INPUT")
	turn.Thinking, turn.Text = "SECRET-THINKING", "done"
	snap := &corpus.Snapshot{
		Turns:       []parse.Turn{turn},
		ToolResults: []parse.ToolResult{{ToolUseID: "t1", Content: "SECRET-OUTPUT"}},
	}
	b, err := json.Marshal(BuildSessionIndex(snap, prices, aggregate.Filter{}, IndexOptions{}))
	if err != nil {
		t.Fatal(err)
	}
	for _, leak := range []string{"SECRET-INPUT", "SECRET-OUTPUT", "SECRET-THINKING", `"steps"`, `"tools"`} {
		if strings.Contains(string(b), leak) {
			t.Errorf("index payload carries %s: %s", leak, b)
		}
	}
	var p struct {
		Sessions []map[string]json.RawMessage `json:"sessions"`
	}
	if err := json.Unmarshal(b, &p); err != nil || len(p.Sessions) != 1 {
		t.Fatalf("unmarshal: %v %s", err, b)
	}
	var keys []string
	for k := range p.Sessions[0] {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	want := "active,commands,cost_usd,duration_ms,failed,family_key,last_activity,model,outcome,project,provider,remainder,session_id,started_at,title,turns"
	if got := strings.Join(keys, ","); got != want {
		t.Errorf("row keys = %s\nwant       %s", got, want)
	}
}


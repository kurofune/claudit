// triageJudgePrefix and implementStepPrefix are the first 200 runes of two
// real prompts from the local corpus (~/.claude/projects), verbatim: the
// workshop triage judge and the Djinn implement step.
const (
	triageJudgePrefix   = "You are a triage judge for this repository's workshop. Decide whether the workshop should build the proposal below: go or no-go, with a one-sentence reason. Read the repository as much as you need, bu"
	implementStepPrefix = "You are running the `implement` step of the Djinn harness for bead claudit-ucr.\n\n<bead>\nID: claudit-ucr\nTitle: Context-cost attribution per tool result in aggregate\nType: task\n\nDescription:\nAttribute "
)

func TestRealPromptPrefixesAre200Runes(t *testing.T) {
	for _, p := range []string{triageJudgePrefix, implementStepPrefix} {
		if n := len([]rune(p)); n != 200 {
			t.Errorf("prefix is %d runes, want 200: %q", n, p)
		}
	}
}


// TestFamilyKey_RealPromptsDifferingOnlyInBeadID: two prompts of one family
// that differ only in their bead id share a key, and the remainder is the
// id. The triage judge's first line names no bead (it blanks only
// "one-sentence"), so its remainder is the bead on its "ID:" line.
func TestFamilyKey_RealPromptsDifferingOnlyInBeadID(t *testing.T) {
	triage := func(id string) string {
		return triageJudgePrefix + "t change nothing.\n\n## The proposal\n\nID: " + id + "\nTitle: Closed beads' leftover worker state expires\nType: epic\n"
	}
	implement := func(id string) string {
		return strings.ReplaceAll(implementStepPrefix, "claudit-ucr", id)
	}
	cases := []struct {
		name string
		mk   func(string) string
		a, b string
		key  string
	}{
		{
			name: "triage judge",
			mk:   triage,
			a:    "djinn-ca6nj",
			b:    "djinn-swi8x",
			key:  "You are a triage judge for this repository's workshop. Decide whether the workshop should build the proposal below: go or no-go, with a _ reason. Read the repository as much as you need, but change nothing.",
		},
		{
			name: "implement step",
			mk:   implement,
			a:    "claudit-ucr",
			b:    "djinn-lyayb",
			key:  "You are running the `implement` step of the Djinn harness for bead _.",
		},
	}
	for _, c := range cases {
		t.Run(c.name, func(t *testing.T) {
			pa, pb := c.mk(c.a), c.mk(c.b)
			ka, kb := FamilyKey(pa), FamilyKey(pb)
			if ka != c.key {
				t.Errorf("FamilyKey(a) = %q, want %q", ka, c.key)
			}
			if ka != kb {
				t.Errorf("keys differ: %q vs %q", ka, kb)
			}
			if got := Remainder(pa); got != c.a {
				t.Errorf("Remainder(a) = %q, want %q", got, c.a)
			}
			if got := Remainder(pb); got != c.b {
				t.Errorf("Remainder(b) = %q, want %q", got, c.b)
			}
		})
	}
}

// TestSessionFamily_FallsBackPastWrapperOnlyPrompts: a session whose first
// prompt is only a caveat block keys on its next prompt with text; a session
// with no textual prompt keys as "(no prompt)".
func TestSessionFamily_FallsBackPastWrapperOnlyPrompts(t *testing.T) {
	caveat := "<local-command-caveat>Caveat: generated by local commands.</local-command-caveat>"
	f := SessionFamily([]string{caveat, "", "deploy build 42 to staging"})
	if f.Key != "deploy build _ to staging" || f.Remainder != "42" || f.Title != "deploy build 42 to staging" {
		t.Errorf("SessionFamily = %+v, want key from the next prompt with text", f)
	}
	none := SessionFamily([]string{caveat, "<system-reminder>x</system-reminder>"})
	if none.Key != "(no prompt)" || none.Remainder != "" || none.Title != "" {
		t.Errorf("SessionFamily(no text) = %+v, want (no prompt)", none)
	}
	if empty := SessionFamily(nil); empty.Key != "(no prompt)" {
		t.Errorf("SessionFamily(nil).Key = %q, want (no prompt)", empty.Key)
	}
}

func TestSessionFamily_TitleCapsAt200Runes(t *testing.T) {
	long := strings.Repeat("é", 250)
	f := SessionFamily([]string{long})
	if n := len([]rune(f.Title)); n != 200 {
		t.Errorf("title = %d runes, want 200", n)
	}
}

// pastedPrompt opens like a real session's prompt (~/.claude/projects,
// 2026-11): a pasted_content block, its opening tag carrying an id, then
// the pasted text; cut to its first sentences and closed.
const pastedPrompt = "\n\n<pasted_content id=\"a9d4\">\nInside this folder, you'll find another folder called SIE AI Craft VTT Files. These are transcripts from videos that I've recorded for a group that I run called AI Craft, where I teach people how to use agent harnesses and how to become an agentic engineer.\nI'm putting together a class.\n</pasted_content>\n"

func TestFamily_PastedContentTitlesByItsFirstLine(t *testing.T) {
	line := "Inside this folder, you'll find another folder called SIE AI Craft VTT Files. These are transcripts from videos that I've recorded for a group that I run called AI Craft, where I teach people how to use agent harnesses and how to become an agentic engineer."
	f := SessionFamily([]string{pastedPrompt})
	if want := truncateRunesPlain(line, titleMaxRunes); f.Title != want {
		t.Errorf("title = %q, want %q", f.Title, want)
	}
	if key, _ := blank(line); f.Key != key {
		t.Errorf("key = %q, want blank(first pasted line) %q", f.Key, key)
	}
	if strings.Contains(f.Title, "pasted_content") || strings.Contains(f.Key, "pasted_content") {
		t.Errorf("title %q or key %q carries the tag", f.Title, f.Key)
	}
	unclosed := SessionFamily([]string{"<pasted_content id=\"x1\">\n\nfix the login bug\nmore"})
	if unclosed.Title != "fix the login bug" {
		t.Errorf("unclosed block title = %q, want the pasted first line", unclosed.Title)
	}
}

func TestFamily_PastedContentUnwrapped(t *testing.T) {
	f := SessionFamily([]string{"<pasted_content id=\"41a8\">\nfix the login bug\nmore</pasted_content>"})
	if f.Title != "fix the login bug" || f.Key != "fix the login bug" {
		t.Errorf("pasted block: title %q key %q, want both %q", f.Title, f.Key, "fix the login bug")
	}
	before := SessionFamily([]string{"look at this\n<pasted_content id=\"41a8\">\nfix the login bug\nmore</pasted_content>"})
	if before.Title != "look at this" || before.Key != "look at this" {
		t.Errorf("text before block: title %q key %q, want both %q", before.Title, before.Key, "look at this")
	}
}
